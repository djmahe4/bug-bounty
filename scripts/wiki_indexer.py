#!/usr/bin/env python3
"""
wiki_indexer.py — deterministic wikilink indexer for the bug-bounty wiki.

Modes
-----
  python scripts/wiki_indexer.py            # build indexes + backlinks
  python scripts/wiki_indexer.py --check    # validate only; exit 1 on broken links
  python scripts/wiki_indexer.py --watch    # rebuild on file changes
  python scripts/wiki_indexer.py --json     # dump graph to stdout

Frontmatter (required on every wiki/*.md):
  ---
  title: Recon Methodology
  category: recon            # meta|fundamentals|recon|exploitation|
                             # methodology|tooling|reporting|practice
  tags: [recon, osint]
  order: 20                  # optional
  aliases: [recon]           # optional
  ---

Wikilinks:
  [[Recon-Methodology]]            -> wiki/Recon-Methodology.md
  [[Recon-Methodology|display]]    -> custom label
  [[tooling/nuclei|Nuclei]]        -> nested path

Backlinks are auto-injected between markers and are safe to re-run:
  <!-- backlinks:auto-start --> ... <!-- backlinks:auto-end -->
"""
from __future__ import annotations
import argparse, json, os, re, sys, tempfile, time
from dataclasses import dataclass, field
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("PyYAML required: pip install pyyaml")

ROOT       = Path(__file__).resolve().parents[1]
WIKI_DIR   = ROOT / "wiki"
INDEX_FILE = WIKI_DIR / "_index.md"
GRAPH_FILE = WIKI_DIR / "_graph.json"
BL_START   = "<!-- backlinks:auto-start -->"
BL_END     = "<!-- backlinks:auto-end -->"
FM_RE      = re.compile(r"^---\s*\n(.*?)\n---\s*\n", re.DOTALL)
WL_RE      = re.compile(r"\[\[([^\]\|#]+)(?:#[^\]\|]+)?(?:\|([^\]]+))?\]\]")
BLK_RE     = re.compile(re.escape(BL_START) + r".*?" + re.escape(BL_END), re.DOTALL)
CATEGORIES = ["meta","fundamentals","recon","exploitation",
              "methodology","tooling","reporting","practice"]

@dataclass
class Page:
    path: Path; slug: str; meta: dict; body: str
    title: str; category: str; tags: list; order: int; aliases: list
    out_links: list = field(default_factory=list)

@dataclass
class Graph:
    pages: dict; incoming: dict; broken: list; orphans: list

def norm(s: str) -> str:
    s = s.strip().strip("/").removesuffix(".md").replace("\\", "/")
    parts = [re.sub(r"[^a-z0-9]+","-",p.lower()).strip("-") for p in s.split("/")]
    return "/".join(p for p in parts if p)

def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".wikitmp-")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        os.replace(tmp, path)
    except BaseException:
        os.unlink(tmp); raise

def parse_page(path: Path):
    raw = path.read_text(encoding="utf-8")
    m = FM_RE.match(raw)
    if not m:
        return None
    try:
        meta = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError as e:
        print(f"  ! frontmatter error in {path}: {e}", file=sys.stderr)
        return None
    body = BLK_RE.sub("", raw[m.end():]).rstrip() + "\n"
    rel = path.relative_to(WIKI_DIR).with_suffix("").as_posix()
    slug = norm(rel)
    tags = meta.get("tags") or []
    if isinstance(tags, str): tags = [tags]
    return Page(path=path, slug=slug, meta=meta, body=body,
        title=meta.get("title") or rel.replace("-"," ").title(),
        category=meta.get("category") or "meta",
        tags=[str(t) for t in tags],
        order=int(meta.get("order") or 999),
        aliases=[norm(a) for a in (meta.get("aliases") or [])])

def scan() -> Graph:
    pages: dict = {}
    if WIKI_DIR.is_dir():
        for path in sorted(WIKI_DIR.rglob("*.md")):
            if path.name.startswith("_"): continue
            p = parse_page(path)
            if p is None: continue
            if p.slug in pages:
                print(f"  ! duplicate slug: {p.slug}", file=sys.stderr); continue
            pages[p.slug] = p
    alias_map = {a: p.slug for p in pages.values() for a in p.aliases}
    broken, incoming = [], {s: set() for s in pages}
    for p in pages.values():
        for raw_t, _ in WL_RE.findall(p.body):
            t = norm(raw_t)
            resolved = t if t in pages else alias_map.get(t)
            if not resolved:
                broken.append((p.slug, raw_t.strip())); continue
            if resolved == p.slug: continue
            p.out_links.append(resolved)
            incoming[resolved].add(p.slug)
    orphans = [s for s, inc in incoming.items() if not inc and s != "home"]
    return Graph(pages, incoming, broken, orphans)

def render_index(g: Graph) -> str:
    lines = ["# Wiki Index", "",
             "> **Auto-generated by `scripts/wiki_indexer.py`. Do not edit.**",
             f"> Pages: {len(g.pages)} · Wikilinks: "
             f"{sum(len(p.out_links) for p in g.pages.values())} · "
             f"Broken: {len(g.broken)} · Orphans: {len(g.orphans)}",
             "", "See also: [[Home]]", ""]
    by_cat: dict = {c: [] for c in CATEGORIES}
    for p in g.pages.values():
        by_cat.setdefault(p.category, []).append(p)
    for cat in sorted(by_cat, key=lambda c:(CATEGORIES.index(c) if c in CATEGORIES else 99, c)):
        ps = sorted(by_cat[cat], key=lambda p:(p.order, p.title.lower()))
        if not ps: continue
        lines += [f"## {cat.title()}", "",
                  "| Page | Tags | Backlinks |", "|------|------|-----------|"]
        for p in ps:
            tags = ", ".join(f"`{t}`" for t in p.tags) or "—"
            lines.append(f"| [[{p.slug}\\|{p.title}]] | {tags} | "
                         f"{len(g.incoming.get(p.slug,()))} |")
        lines.append("")
    if g.broken:
        lines += ["## Broken Wikilinks", ""]
        for src, tgt in sorted(g.broken):
            lines.append(f"- `{src}` → `[[{tgt}]]`")
        lines.append("")
    if g.orphans:
        lines += ["## Orphans (no incoming links)", ""]
        for s in sorted(g.orphans): lines.append(f"- [[{s}]]")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"

def render_graph(g: Graph) -> str:
    return json.dumps({
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "pages": {s: {"title": p.title, "category": p.category,
                      "tags": p.tags,
                      "out_links": sorted(set(p.out_links)),
                      "in_links": sorted(g.incoming.get(s, set()))}
                  for s, p in g.pages.items()},
        "broken":  sorted(g.broken),
        "orphans": sorted(g.orphans),
    }, indent=2, sort_keys=True) + "\n"

def inject_backlinks(g: Graph) -> int:
    modified = 0
    for slug, page in g.pages.items():
        incoming = sorted(g.incoming.get(slug, set()))
        body = BLK_RE.sub("", page.body).rstrip() + "\n"
        if incoming:
            lines = "\n".join(
                f"- [[{s}\\|{g.pages[s].title}]]" if s in g.pages
                else f"- [[{s}]]" for s in incoming)
            body += f"\n{BL_START}\n\n## Backlinks\n\n{lines}\n\n{BL_END}\n"
        else:
            body += f"\n{BL_START}\n\n_No backlinks yet._\n\n{BL_END}\n"
        fm = yaml.safe_dump(page.meta, sort_keys=False, allow_unicode=True).strip()
        new_text = f"---\n{fm}\n---\n\n{body}"
        old = page.path.read_text(encoding="utf-8")
        if not old.endswith("\n"): old += "\n"
        if old != new_text:
            atomic_write(page.path, new_text); modified += 1
    return modified

def build(quiet: bool = False) -> Graph:
    g = scan()
    if not quiet: print(f"• scanned {len(g.pages)} pages")
    atomic_write(INDEX_FILE, render_index(g))
    atomic_write(GRAPH_FILE, render_graph(g))
    n = inject_backlinks(g)
    if not quiet:
        print(f"• wrote {INDEX_FILE.relative_to(ROOT)} and {GRAPH_FILE.relative_to(ROOT)}")
        print(f"• updated backlinks on {n} page(s)")
        if g.broken:
            print(f"• ✗ {len(g.broken)} broken wikilink(s):", file=sys.stderr)
            for src, tgt in g.broken:
                print(f"    {src} -> [[{tgt}]]", file=sys.stderr)
    return g

def check() -> int:
    g = scan(); code = 0
    if g.broken:
        print(f"✗ {len(g.broken)} broken wikilink(s):", file=sys.stderr)
        for src, tgt in g.broken:
            print(f"    {src} -> [[{tgt}]]", file=sys.stderr)
        code = 1
    if g.orphans:
        print(f"⚠ {len(g.orphans)} orphan page(s) (warning):")
        for s in g.orphans: print(f"    {s}")
    if code == 0:
        print(f"✓ {len(g.pages)} pages, 0 broken links")
    return code

def watch() -> None:
    print(f"👁  watching {WIKI_DIR.relative_to(ROOT)}/ …")
    build(); seen: dict = {}
    try:
        while True:
            changed = False
            for path in WIKI_DIR.rglob("*.md"):
                if path.name.startswith("_"): continue
                m = path.stat().st_mtime
                if seen.get(path) != m: seen[path] = m; changed = True
            if changed: build()
            time.sleep(1.0)
    except KeyboardInterrupt:
        print("\nstopped")

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--watch", action="store_true")
    ap.add_argument("--json",  action="store_true")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()
    if args.check: return check()
    if args.watch: watch(); return 0
    g = build(quiet=args.quiet)
    if args.json: print(render_graph(g))
    return 0 if not g.broken else 1

if __name__ == "__main__":
    sys.exit(main())